-- =====================================================
-- TABELA DE VÍNCULO ENTRE SISTEMAS E TIPOS DE PRODUTIVIDADE
-- =====================================================

-- Tabela de vínculo entre Sistemas e Tipos de Produtividade
CREATE TABLE SISTEMA_TIPO_PRODUTIVIDADE (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
    CODSISTEMA INTEGER NOT NULL,
    CODTIPOPRODUTIVIDADE INTEGER NOT NULL,
    ATIVO BOOLEAN DEFAULT TRUE,
    DTHR_CRIACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT SISTEMA_TIPO_PRODUTIVIDADE_PK PRIMARY KEY (ID),
    CONSTRAINT SISTEMA_TIPO_PRODUTIVIDADE_UK UNIQUE (CODSISTEMA, CODTIPOPRODUTIVIDADE),
    CONSTRAINT SISTEMA_TIPO_PRODUTIVIDADE_SISTEMA_FK FOREIGN KEY (CODSISTEMA) REFERENCES SISTEMAS(CODSISTEMA),
    CONSTRAINT SISTEMA_TIPO_PRODUTIVIDADE_TIPO_FK FOREIGN KEY (CODTIPOPRODUTIVIDADE) REFERENCES TIPOPRODUTIVIDADE(CODTIPOPRODUTIVIDADE)
);

-- Índices para performance
CREATE INDEX IDX_SISTEMA_TIPO_SISTEMA ON SISTEMA_TIPO_PRODUTIVIDADE(CODSISTEMA);
CREATE INDEX IDX_SISTEMA_TIPO_TIPO ON SISTEMA_TIPO_PRODUTIVIDADE(CODTIPOPRODUTIVIDADE);
CREATE INDEX IDX_SISTEMA_TIPO_ATIVO ON SISTEMA_TIPO_PRODUTIVIDADE(ATIVO);

